#!/usr/bin/env python3
"""Independent Pandas CSV profiling, with optional pure-Python JSON comparison."""
import argparse
import json
import math
from pathlib import Path
import pandas as pd

MISSING = {'', 'n/a', 'na', 'null', 'none', 'nan'}
NUMBER = r'[+-]?(?:\d+|\d{1,3}(?:,\d{3})+)(?:\.\d+)?(?:[eE][+-]?\d+)?'

def classify(series):
    """Infer logical type without importing any pure-Python analysis code."""
    present = series.dropna()
    if present.empty:
        return 'empty', None
    text = present.str.replace(r'^\$\s*', '', regex=True)
    valid = text.str.fullmatch(NUMBER)
    numeric = pd.to_numeric(text.where(valid).str.replace(',', '', regex=False), errors='coerce')
    numeric = numeric.where(numeric.map(lambda v: pd.notna(v) and math.isfinite(v)))
    if numeric.notna().all():
        return ('integer' if numeric.mod(1).eq(0).all() else 'float'), numeric
    dates = pd.to_datetime(present, format='%Y-%m-%d', errors='coerce')
    if dates.notna().all():
        return 'date', None
    if (present.str.startswith('{') & present.str.endswith('}')).all():
        return 'structured_text (dictionary-like)', None
    if (present.str.startswith('[') & present.str.endswith(']')).all():
        return 'structured_text (list-like)', None
    return ('mixed_numeric_text' if numeric.notna().any() else 'text'), numeric

def analyze(path):
    # Preserve original strings so Pandas does not silently choose NA tokens/types.
    frame = pd.read_csv(path, dtype='string', keep_default_na=False, encoding='utf-8-sig')
    typed = frame.copy()
    report = dict(rows=len(frame), columns=len(frame.columns),
                  std_dev_convention='sample (ddof=1)', column_stats={})
    for name in frame:
        s = frame[name].str.strip()
        s = s.mask(s.str.casefold().isin(MISSING))
        frame[name] = s
        kind, numbers = classify(s)
        stats = dict(inferred_type=kind, missing=int(s.isna().sum()),
                     missing_percentage=float(s.isna().mean()*100) if len(s) else 0.0)
        if kind in ('integer', 'float'):
            typed[name] = pd.to_numeric(s.str.replace(r'^\$\s*', '', regex=True).str.replace(',', '', regex=False))
            stats.update(count=int(numbers.count()), mean=float(numbers.mean()),
                         minimum=float(numbers.min()), maximum=float(numbers.max()),
                         std_dev=float(numbers.std(ddof=1)) if len(numbers)>1 else None,
                         median=float(numbers.median()))
        else:
            typed[name] = s
            counts = s.value_counts(dropna=True)
            # Explicit alphabetical tie-breaking, matching the documented baseline.
            top = sorted(((str(k), int(v)) for k,v in counts.items()), key=lambda x: (-x[1], x[0]))
            stats.update(count=int(s.count()), unique=int(s.nunique(dropna=True)),
                         mode=top[0][0] if top else None,
                         mode_frequency=top[0][1] if top else 0, top_5=top[:5])
            if kind == 'mixed_numeric_text':
                stats['numeric_parseable_count'] = int(numbers.count())
        report['column_stats'][name] = stats
    return typed, report

def compare(report, baseline):
    """Exact structural/count comparison; tolerance only for mean and std_dev."""
    failures, differences = [], []
    checked = 0
    for key in ('rows', 'columns', 'std_dev_convention'):
        if report[key] != baseline.get(key):
            failures.append(key)
    if set(report['column_stats']) != set(baseline['column_stats']):
        failures.append('column names')
    for name, expected in baseline['column_stats'].items():
        actual = report['column_stats'].get(name, {})
        for metric, value in expected.items():
            checked += 1
            observed = actual.get(metric)
            if metric in ('mean', 'std_dev') and value is not None and observed is not None:
                equal = math.isclose(value, observed, rel_tol=1e-12, abs_tol=1e-12)
                if observed != value:
                    differences.append(dict(column=name, metric=metric, absolute_difference=abs(observed-value)))
            else:
                # Normalize tuples from value_counts to JSON arrays.
                equal = json.loads(json.dumps(observed)) == value
            if not equal:
                failures.append(f'{name}.{metric}: {observed!r} != {value!r}')
    return dict(passed=not failures, metrics_checked=checked, failures=failures,
                tolerance=dict(relative=1e-12, absolute=1e-12), floating_point_differences=differences)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('csv_path', type=Path)
    parser.add_argument('--baseline', type=Path, help='JSON generated by pure_python_stats.py')
    parser.add_argument('--json-output', type=Path)
    parser.add_argument('--comparison-output', type=Path)
    args = parser.parse_args()
    try:
        df, report = analyze(args.csv_path)
        print('Pandas version:', pd.__version__)
        print('Shape:', df.shape)
        print('\nDTYPES\n', df.dtypes.to_string())
        print('\nINFO'); df.info(show_counts=True)
        numeric = df.select_dtypes(include='number')
        categorical = df.select_dtypes(exclude='number')
        if len(numeric.columns):
            print('\nNUMERIC describe()\n', numeric.describe().to_string())
        if len(categorical.columns):
            print('\nNON-NUMERIC describe()\n', categorical.describe().to_string())
        print('\nPER-COLUMN STATISTICS (missing_percentage is 0–100)')
        print(json.dumps(report, indent=2, ensure_ascii=False, allow_nan=False))
        if args.json_output:
            args.json_output.write_text(json.dumps(report, indent=2, ensure_ascii=False, allow_nan=False)+'\n', encoding='utf-8')
        if args.baseline:
            result = compare(report, json.loads(args.baseline.read_text(encoding='utf-8')))
            print('\nCOMPARISON\n', json.dumps(result, indent=2))
            if args.comparison_output:
                args.comparison_output.write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
            if not result['passed']:
                return 1
        elif args.comparison_output:
            parser.error('--comparison-output requires --baseline')
        return 0
    except (OSError, ValueError, pd.errors.ParserError) as error:
        parser.exit(1, f'Error: {error}\n')

if __name__ == '__main__':
    raise SystemExit(main())
